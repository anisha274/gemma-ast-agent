"""Recompute every number quoted in paper/writeup.md from results/kaggle_runs.json.

    python results/analyze.py > results/analysis.md
"""
from __future__ import annotations

import json
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from ast_agent.eval import mcnemar_exact, wilson  # noqa: E402

D = json.load(open(os.path.join(os.path.dirname(__file__), "kaggle_runs.json")))
N = 50
TASKS = range(1, N + 1)
CONDS = ["file", "ast_graph", "ast_graph_sc", "full", "oracle"]
MODELS = {"e2b": "Gemma 4 E2B", "e4b": "Gemma 4 E4B"}


def solved(model: str, cond: str) -> set[int]:
    return {int(k) for k in D["resolved"][model][cond]}


def pct(x: float) -> str:
    return f"{100 * x:.0f}%"


print("# Analysis of the Kaggle runs\n")
print("Generated by `results/analyze.py` from `results/kaggle_runs.json`.\n")

print("## Resolve rates (n = 50, Wilson 95% CI)\n")
print("| Condition | " + " | ".join(MODELS.values()) + " | Symbol hit |")
print("|---|" + "---|" * (len(MODELS) + 1))
for c in CONDS:
    cells = []
    for m in MODELS:
        k = len(solved(m, c))
        lo, hi = wilson(k, N)
        cells.append(f"{k}/50 = {pct(k / N)} [{pct(lo)}-{pct(hi)}]")
    sh = D["summary"]["e4b"][c]["symbol_hit"]
    print(f"| {c} | " + " | ".join(cells) + f" | {pct(sh)} |")

print("\n## Paired comparisons (exact two-sided McNemar)\n")
pairs = [("file", "ast_graph"), ("ast_graph", "ast_graph_sc"), ("ast_graph_sc", "full"),
         ("ast_graph", "full"), ("file", "full"), ("oracle", "full"), ("file", "oracle")]
print("| A -> B | Model | only A | only B | p |")
print("|---|---|---|---|---|")
for a, b in pairs:
    for m, name in MODELS.items():
        sa, sb = solved(m, a), solved(m, b)
        print(f"| {a} -> {b} | {name} | {len(sa - sb)} | {len(sb - sa)} | "
              f"{mcnemar_exact(len(sa - sb), len(sb - sa)):.4f} |")

print("\n## Determinism check\n")
for m, name in MODELS.items():
    first = {int(k) for k, v in D["resolved"][m]["ast_graph_sc"].items() if v == 1}
    print(f"- {name}: tasks solved on attempt 1 of `ast_graph_sc` == tasks solved by single-attempt "
          f"`ast_graph`: {first == solved(m, 'ast_graph')} ({len(first)} tasks)")

print("\n## When self-correcting runs succeed (attempt number)\n")
for m, name in MODELS.items():
    for c in ("ast_graph_sc", "full"):
        att = Counter(D["resolved"][m][c].values())
        print(f"- {name} `{c}`: attempt 1: {att[1]}, attempt 2: {att[2]}, attempt 3: {att[3]}")

print("\n## Coverage\n")
for m, name in MODELS.items():
    union = set().union(*(solved(m, c) for c in CONDS))
    print(f"- {name}: solved by at least one condition: {len(union)}/50; by none: {N - len(union)}/50")
e2b_all = set().union(*(solved("e2b", c) for c in CONDS))
e4b_all = set().union(*(solved("e4b", c) for c in CONDS))
print(f"- Tasks E2B solves in some condition but E4B never does: {sorted(e2b_all - e4b_all)}")

print("\n## Resolve rate by mutation operator (Gemma 4 E4B)\n")
kinds = D["task_kinds"]
by_kind = Counter(kinds.values())
print("| Operator | Tasks | file | ast_graph | full | oracle |")
print("|---|---|---|---|---|---|")
for kind in sorted(by_kind):
    ids = {int(t) for t, k in kinds.items() if k == kind}
    row = [f"{len(ids & solved('e4b', c))}/{len(ids)}" for c in ("file", "ast_graph", "full", "oracle")]
    print(f"| {kind} | {len(ids)} | " + " | ".join(row) + " |")

print("\n## Cost per task\n")
print("| Condition | Model | Total tokens | Model seconds | Tokens vs file |")
print("|---|---|---|---|---|")
for m, name in MODELS.items():
    base = D["summary"][m]["file"]["tokens_per_task"]
    for c in CONDS:
        s = D["summary"][m][c]
        print(f"| {c} | {name} | {s['tokens_per_task']} | {s['model_s_per_task']} | "
              f"{s['tokens_per_task'] / base:.2f}x |")
